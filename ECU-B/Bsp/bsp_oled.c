void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
    if(((uint8_t)ch < 32U) || ((uint8_t)ch > 127U)) ch = 32;
    uint8_t idx = ch - 32;
    for(uint8_t i = 0; i < 6; i++)
    {
        uint8_t line = g_font_6x8[idx][i];
        for(uint8_t j = 0; j < 8; j++)
        {
            if(line & (1 << j))
                OLED_DrawPixel(x + i, y + j, 1);
            else
                OLED_DrawPixel(x + i, y + j, 0);
        }
    }
}

void OLED_ShowString(uint8_t x, uint8_t row, const char *str)
{
    while(*str)
    {
        OLED_ShowChar(
            x,
            row * 8,
            *str);

        str++;

        x += 6;

        if(x > 122)
        {
            x = 0;
            row++;

            if(row >= 8)
                break;
        }
    }
}
